class Command(BaseCommand):
    help = 'Добавляет услуги нового каталога без создания работ'

    def handle(self, *args, **options):
        created = 0
        updated = 0

        for category_order, (category_name, services) in enumerate(CATALOG):
            category, _ = Category.objects.get_or_create(
                slug=slugify(category_name, allow_unicode=True),
                defaults={
                    'name': category_name,
                    'description': '',
                    'sort_order': category_order,
                    'is_active': True,
                },
            )
            category.name = category_name
            category.sort_order = category_order
            category.is_active = True
            if category_name == 'Диагностика и сопровождение':
                category.description = (
                    'Осмотр инженерных систем, поиск неисправностей, рекомендации '
                    'и сопровождение сантехнических работ от закупки до установки.'
                )
            category.save(update_fields=['name', 'description', 'sort_order', 'is_active'])
            for sort_order, (name, description, price) in enumerate(services):
                _, was_created = SubCategory.objects.update_or_create(
                    category=category,
                    name=name,
                    defaults={
                        'description': description,
                        'approximate_price': price,
                        'sort_order': sort_order,
                        'is_active': True,
                    },
                )
                if was_created:
                    created += 1
                else:
                    updated += 1

        self.stdout.write(self.style.SUCCESS(f'Готово: создано {created}, обновлено {updated}'))
