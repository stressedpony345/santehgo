def matches(service_name, key):
    name = service_name.lower()
    if key == 'машин':
        return 'машина' in name
    if key == 'кран':
        return ('кран' in name or 'арматур' in name) and 'смесител' not in name and 'счётчик' not in name
    if key == 'труб':
        return any(x in name for x in ('труб', 'полиэтилен', 'металлопласт', 'полипропилен', 'трубопровод')) and 'канализац' not in name and 'стояк' not in name
    return key in name


def works_for(service):
    if service.name in CONSULTING:
        return CONSULTING[service.name]

    items = list(COMMON)
    for key, works in PROFILES.items():
        if matches(service.name, key):
            items.extend(works)

    # Несколько названий требуют смысловой профиль, который не следует из одного слова.
    category_name = service.category.name.lower()
    if 'прочистка канализации' in category_name and not any(x[0] == 'Прочистка ручным тросом' for x in items):
        items.extend(PROFILES['засор'])
    if 'канализационных труб' in category_name and not any(x[0] == 'Замена участка канализационной трубы' for x in items):
        items.extend(PROFILES['канализац'])
    if 'отопительных приборов' in category_name and len(items) == len(COMMON):
        items.extend(PROFILES['радиатор'])

    # Удаляем совпадения, если услуга получила два близких профиля.
    unique = []
    seen = set()
    for item in items:
        if item[0] not in seen:
            unique.append(item)
            seen.add(item[0])
    return unique


class Command(BaseCommand):
    help = 'Полностью заменяет работы каталога подробным локальным перечнем'

    @transaction.atomic
    def handle(self, *args, **options):
        old_count = Work.objects.count()
        Work.objects.all().delete()
        created = 0
        uncovered = []

        for service in SubCategory.objects.select_related('category').all():
            works = works_for(service)
            if len(works) <= len(COMMON) and service.name not in CONSULTING:
                uncovered.append(service.name)
            base = max(Decimal('1'), service.approximate_price)
            for sort_order, (name, description, price) in enumerate(works):
                # Для крупных монтажных операций цена карточки услуги точнее общего шаблона.
                if name == 'Установка нового оборудования':
                    price = max(Decimal(price), base)
                Work.objects.create(
                    service=service,
                    name=name,
                    description=description,
                    price=price,
                    sort_order=sort_order,
                    is_active=True,
                )
                created += 1

        self.stdout.write(self.style.SUCCESS(
            f'Готово: удалено старых работ {old_count}, создано подробных работ {created}'
        ))
        if uncovered:
            self.stdout.write(self.style.WARNING(
                'Только базовые операции у услуг: ' + ', '.join(uncovered)
            ))
